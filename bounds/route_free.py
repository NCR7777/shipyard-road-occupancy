"""Route-free bound T1'' and route-fixed comparison R (proof in the paper's appendix).

Loaded routes are chosen by the linear programme. Commodity = (origin node, destination node, width B); path variables are
generated by column generation. The key path is the shortest path used by the simulation (Net.path), so the solution of the
first master problem is R (loaded routes fixed to the shortest paths, same relaxations as T1''), and T1' ≤ R ≤ T1''. The
occupancy of each task is split into two parts:
  Route-independent (exact expectation over the mix, with the true vehicle length): origin window; destination window
    (unloading + the stop resource held from entering the last arc); the tail on the last road when pulling into a bay or
    stopping at an entrance; crane rows.
  Route-dependent (summed arc by arc, linear in the flows): road L/v and the tail clearance on leaving at a map node; junction
    passage (D + vehicle length + longitudinal clearance)/v (not at the destination).
    The vehicle length is always its lower bound plat_len; the turn sweep is not counted. A simple path passes each junction
    at most once and does not pass through its own origin or destination; it uses the same road at most twice, and only when
    both its origin and destination lie on that road (the road carries stops; these resources are found from the out-arcs of
    stop nodes, on sectioned networks they are the sections that contain the stops, system.stop_ret): so only on these
    resources is the tail on leaving at a map node truncated to "the shortest distance before entering the same road again"
    (ret); everywhere else it is counted in full (simple-path reduction lemma in the paper's appendix).
The width-packing rows still hold: the share of a given B on a given resource is constant, so the occupancy rows are linear
in the flows. The empty-run part is that of T1' (bound._system), with only the tail on leaving at a map node on roads with
stops truncated by ret in the same way (system.empty_block; proof in the paper's appendix).
Pricing is a shortest-path computation on the node graph: the turn permissions of this model forbid only U-turns (except at
dead-end entrances, as checked for both yards), so every simple path on the node graph is a legal route.
Each round computes a Lagrangian certificate UB from the dual prices of the master problem: first μ⁺ = max(μ, 0), then ν is
repaired to be strictly feasible for the empty-run coefficients, and the formula is applied (valid for any route, independent
of the solver tolerances); the reported T1'' is the minimum UB over the rounds, equal to the master value at convergence.
Door granularity (the door road change of Net): when the origin or destination is at a door, the door (entrance node) is held
only while passing, (D + vehicle length + longitudinal clearance)/v, independent of the route, so it is counted in the
route-independent part; loading and unloading take place at the bay inside the door (a stop resource).
"""
