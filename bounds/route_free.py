NK = len(DFF_K)


class OnPath:
    """Network proxy: path() returns the given arc sequence, everything else uses the original network. Builds the T1'
    windows on any route by the same rules as network.leg and bound.task_windows (true vehicle length, turn sweep,
    destination from entering the last road, union of windows); back-substitution and the check of Assumption 1' both use
    it, so there is no second implementation."""

    def __init__(self, net, arcs):
        self._net, self._arcs = net, list(arcs)

    def __getattr__(self, k):
        return getattr(self._net, k)

    def path(self, src, dst):
        return self._arcs

    def leg(self, *a, **kw):
        return Net.leg(self, *a, **kw)


def t1_on_path(net, p, cap, size, task, arcs):
    """Windows in the T1' form for a task driving along the given route arcs: {resource: length of the union} (with
    arcs = Net.path this is system.t1_times)."""
    by, _ = task_windows(OnPath(net, arcs), p, cap, size, task, tight=True)
    return {r: union(iv) for r, iv in by.items()}


class RouteFree:
    """R and T1'' of a mix (with an optional part fixed in absolute number, fixed = (mix, number per day))."""

    def __init__(self, net, p, mix, fixed=None):
        self.net, self.p = net, p
        self.cap, self.size = net.capacities(p)
        self.res_list = sorted(self.cap)
        self.ri = {r: i for i, r in enumerate(self.res_list)}
        self.nr = len(self.res_list)
        self.v, self.lc, self.Lmin = p["v_loaded"], p["long_clear"], p["plat_len"]
        parts = [(mix, None)] + ([fixed] if fixed else [])
        Lmax = max(lv for m, _ in parts for _, _, bl in m for (_, lv), _ in bl)
        self.tail_arcs = {a for a, x in enumerate(net.arc) if not x[1].startswith("S|")}      # arcs leaving a road (head is a map node)
        self.bnodes = {f"S|{rid}|{x}" for rid, xs in net.edges.items() for x in xs}         # section boundaries (sectioned networks; used by btail)
        self.ret = stop_ret(net, Lmax + self.lc)
        self.in_arcs = collections.defaultdict(list)
        for a, x in enumerate(net.arc):
            self.in_arcs[x[1]].append(a)
        # stop nodes of drive-in bays are not on section boundaries (min_gap of Net._section), so all arcs into one lie on the same section (fixed_times uses this section)
        assert all(len({net.arc[a][3] for a in self.in_arcs[s["node"]]}) == 1 for s in net.stops.values() if s["mode"] == "pull_in")
        self.min_in = {n: min(net.arc[a][2] for a in v) for n, v in self.in_arcs.items()}
        self.nodes = sorted({x for a in net.arc for x in a[:2]})
        self.ni = {n: i for i, n in enumerate(self.nodes)}
        self.tidx = np.array([self.ni[a[0]] for a in net.arc])
        self.hidx = np.array([self.ni[a[1]] for a in net.arc])
        self.alen = np.array([a[2] for a in net.arc])
        # route-dependent per-arc times (vehicle length at its lower bound): road rows and the junction row at the arc head
        self.road_t = np.array([(a[2] + self._tail(i, self.Lmin)) / self.v for i, a in enumerate(net.arc)])
        self.hold = {n: (self.size[n] + self.Lmin + self.lc) / self.v for n in net.node_res}
        self.Bs = sorted({B for m, _ in parts for _, _, bl in m for (B, _), _ in bl})
        self.parts = [self._part(m, n6) for m, n6 in parts]
        w, t, bl = next(x for x in mix if not x[1].get("lift"))
        self.dummy = dict(t, B=bl[0][0][0], Lv=bl[0][0][1])

    # ------------------------------------------------------------ times of a task
    def _tail(self, a, L, caps=True):
        """Tail clearance distance on the road after driving arc a: vehicle length L + longitudinal clearance if the head of a
        is a map node, truncated by ret on roads with stops; otherwise 0."""
        if a not in self.tail_arcs:
            return 0.0
        return min(L + self.lc, self.ret[a]) if caps and a in self.ret else L + self.lc

    def fixed_times(self, t, Lv, lv_route=False, caps=True):
        """Route-independent part (true vehicle length Lv). lv_route and caps only affect the part already counted on the arc,
        which is subtracted from "the tail on the last road when stopping at an entrance"."""
        net, p, v = self.net, self.p, self.v
        if t.get("lift"):
            return {("c", net.stops[t["d"]]["ent"]): p["crane_cycle_s"]}
        so, sd = net.stops[t["o"]], net.stops[t["d"]]
        out, tail, same = collections.defaultdict(float), (Lv + self.lc) / v, so["node"] == sd["node"]
        door = lambda n: (self.size[n] + Lv + self.lc) / v       # passage through the door (door granularity)
        x = p["load_s"]                       # origin: [−loading, tail clearance]; a roadside origin counts only loading, leaving its road is counted in the per-arc part
        if so["mode"] != "on_road" and not same:
            x += tail
        out[so["res"]] += x
        if so["mode"] == "door" and not same:
            out[("n", so["node"])] += door(so["node"])
        out[sd["res"]] += p["unload_s"]       # destination: [arrival, end of unloading]
        if not same:
            n = sd["node"]
            if sd["mode"] != "on_road":       # drive-in bay, entrance: the stop resource is requested with the last road and held at least from entering the last arc
                out[sd["res"]] += self.min_in[n] / v
            if sd["mode"] == "pull_in":       # after pulling into a drive-in bay the tail leaves its section (all arcs into the stop node lie on this section)
                out[("r", net.arc[self.in_arcs[n][0]][3])] += tail
            elif sd["mode"] in ("node", "door") and len(self.in_arcs[n]) == 1:     # entrance with a single incoming arc: the vehicle stops to unload, the tail on the last road counts in full
                a = self.in_arcs[n][0]
                out[("r", net.arc[a][3])] += tail - self._tail(a, Lv if lv_route else self.Lmin, caps) / v
            if sd["mode"] == "door":
                out[("n", n)] += door(n)
        if t["flow"] == "P6" and ("c", sd["ent"]) in self.cap:
            out[("c", sd["ent"])] += p["crane_cycle_s"]
        return out

    def path_times(self, arcs, Lv, lv_route=False, caps=True, sweep=False, btail=False):
        """Route-dependent part (per arc): road L/v + tail clearance on leaving at a map node; intermediate junctions
        (D + vehicle length + longitudinal clearance)/v.
        lv_route (true vehicle length), caps=False (no truncation), sweep (turn sweep) and btail (tail at section boundaries)
        are used only to trace the sources of R − T1': on sectioned networks a vehicle that has crossed a section boundary
        still has its tail in the previous section; the T1' windows count it, R and T1'' count the tail only at road ends, as
        in the paper's clearing terms κ_a (a relaxation)."""
        net, v, out = self.net, self.v, collections.defaultdict(float)
        L_r = Lv if lv_route else self.Lmin
        for i, a in enumerate(arcs):
            _, h, L, rid, _ = net.arc[a]
            out[("r", rid)] += (L + (L_r + self.lc if btail and h in self.bnodes else self._tail(a, L_r, caps))) / v
            if i + 1 < len(arcs) and h in net.node_res:
                y = (self.size[h] + L_r + self.lc) / v
                if sweep and net.turn_deg(a, arcs[i + 1]) >= self.p["turn_deg"]:
                    y += self.p["turn_sweep_s"]
                out[("n", h)] += y
        return out

    def route_times(self, t, lv_route=False, caps=True, sweep=False, dest=False, btail=False):
        """Occupancy of a task with its route fixed to the shortest path (the R convention). Four switches restore the T1'
        form term by term: true vehicle length, no truncation, turn sweep, and the destination stop resource held from
        entering the last road (rather than the last arc) together with the tail at entrances with several incoming arcs;
        with all four restored this gives the T1' windows. Sectioned networks have a fifth switch, btail (tail at section
        boundaries; no effect on whole-road networks, which have no section boundaries)."""
        Lv = t["Lv"]
        out = self.fixed_times(t, Lv, lv_route, caps)
        if t.get("lift"):
            return out
        so, sd = self.net.stops[t["o"]], self.net.stops[t["d"]]
        if so["node"] == sd["node"]:
            return out
        arcs = self.net.path(so["node"], sd["node"])
        for r, x in self.path_times(arcs, Lv, lv_route, caps, sweep, btail).items():
            out[r] += x
        if dest and sd["mode"] != "on_road":
            last = self.net.arc[arcs[-1]]
            run = sum(self.net.arc[a][2] for a in arcs[len(arcs) - next(
                (i for i, a in enumerate(reversed(arcs)) if self.net.arc[a][3:] != last[3:]), len(arcs)):])
            out[sd["res"]] += (run - self.min_in[sd["node"]]) / self.v
            if sd["mode"] in ("node", "door") and len(self.in_arcs[sd["node"]]) > 1:
                out[("r", last[3])] += (Lv + self.lc - self._tail(arcs[-1], Lv if lv_route else self.Lmin, caps)) / self.v
        return out

    # ------------------------------------------------------------ mix -> keys and integrated times
    def _part(self, mix, n6):
        """One part of the mix: integrated times of the route-independent part, net node outflow, the probabilities q of the
        keys (origin node, destination node) × B, and the key paths."""
        F = Loads(self.net, self.p, mix, lambda t: self.fixed_times(t, t["Lv"]), self.res_list)
        q = collections.defaultdict(lambda: np.zeros(len(self.Bs)))
        for w, t, bl in mix:
            if t.get("lift"):
                continue
            o, d = self.net.stops[t["o"]]["node"], self.net.stops[t["d"]]["node"]
            if o == d:
                continue
            for (B, _), pr in bl:
                q[(o, d)][self.Bs.index(B)] += w * pr
        pairs = sorted(q)
        paths = [self.net.path(o, d) for o, d in pairs]
        rows = np.repeat(np.arange(len(pairs)), [len(x) for x in paths])
        cols = np.concatenate([np.array(x, dtype=int) for x in paths]) if pairs else np.zeros(0, int)
        Pinc = csr_matrix((np.ones(len(cols)), (rows, cols)), shape=(len(pairs), len(self.net.arc)))
        Q = np.array([q[k] for k in pairs]).reshape(len(pairs), len(self.Bs))
        X = np.zeros((NK, self.nr))           # the last arc of a key path counts the junction passage at the destination; subtract it (not counted at the destination)
        for (o, d), qq in zip(pairs, Q):
            if d in self.hold:
                X[:, self.ri[("n", d)]] += qq.sum() * self.hold[d]
        return dict(F=F, n6=n6, pairs=pairs, paths=paths, Pinc=Pinc, Q=Q, X=X,
                    o=np.array([self.ni[o] for o, _ in pairs], dtype=int), d=np.array([self.ni[d] for _, d in pairs], dtype=int),
                    len0=Pinc @ self.alen)

    def arc_matrix(self, S, j):
        """Per-arc coefficients E (3·nr × number of arcs) for width B_j: road rows road_t · u^(k), the junction row of the arc
        head hold (a loaded vehicle's share on a junction is 1)."""
        rows, cols, vals = [], [], []
        for a, (_, h, _, rid, _) in enumerate(self.net.arc):
            i = self.ri[("r", rid)]
            for k in range(NK):
                rows.append(k * self.nr + i); cols.append(a); vals.append(self.road_t[a] * S[i, j, k])
            if h in self.hold:
                i = self.ri[("n", h)]
                for k in range(NK):
                    rows.append(k * self.nr + i); cols.append(a); vals.append(self.hold[h])
        return csr_matrix((vals, (rows, cols)), shape=(NK * self.nr, len(self.net.arc))).tocsc()

    # ------------------------------------------------------------ column generation
    def _setup(self, cap, rhs):
        """Coefficients for one set of capacities and right-hand sides: E (per-arc coefficients of each width class), fx
        (route-independent part, destination junction subtracted), the empty-run block, the capacities Hvec, the expected
        occupancy base of a task on the key paths, the right-hand side fix taken by the fixed part, and the conservation
        right-hand side beq."""
        net, p, nr = self.net, self.p, self.nr
        S = share_table(net, p, cap, self.res_list, self.Bs)
        E = [self.arc_matrix(S, j) for j in range(len(self.Bs))]
        Aeq_e, Aub_e, _ = empty_block(net, p, cap, self.size, self.dummy, self.ret)
        fx = [P_["F"].abar(cap).reshape(-1) - P_["X"].reshape(-1) for P_ in self.parts]
        base = [f + sum(E[j] @ (P_["Pinc"].T @ P_["Q"][:, j]) for j in range(len(self.Bs))) for f, P_ in zip(fx, self.parts)]
        n6 = self.parts[1]["n6"] if len(self.parts) > 1 else 0.0
        fix = n6 * base[1] if n6 else np.zeros(NK * nr)
        beq = n6 * self.parts[1]["F"].on if n6 else np.zeros(len(self.nodes))
        return E, fx, Aeq_e, Aub_e, capacity_vec(p, self.res_list, rhs), base, fix, beq, n6

    def ub(self, mu, nu, cap=None, rhs=None):
        """Lagrangian certificate for any (μ, ν) (tasks/day, including the fixed part): first μ⁺ = max(μ, 0), ν repaired to be
        strictly feasible for the empty-run coefficients (_fix_nu), then the formula of the proof in the paper's appendix.
        Never below T1'' for any μ, ν (test test_certificate_robust)."""
        E, fx, _, Aub_e, Hvec, *_, n6 = self._setup(cap or self.cap, rhs)
        return self._price(E, fx, Aub_e, mu, {}, nu, Hvec, 0)[1] + n6

    def solve(self, cap=None, rhs=None, pool=None, tol=1e-7, maxit=400, add=4000, R_only=False, log=None, top=10):
        """Returns a dict: T1pp (minimum Lagrangian certificate over the rounds, tasks/day, including the fixed part), master
        (value of the master problem), R (first master problem = loaded routes fixed to the shortest paths), binding
        resources and dual prices (the first `top`), detour statistics, the column pool pool (warm start for the next solve),
        the duals and the solution sol of the last round, the iteration log and the problem size. cap: changed capacities
        (e.g. one road widened by 1 m); rhs = {resource: factor}: the capacity of all rows of that resource is multiplied by
        the factor.
        If pool is given, the first master problem already contains these columns and R is not reported."""
        t0 = time.time()
        net, nr, A = self.net, self.nr, len(self.net.arc)
        cap = cap or self.cap
        E, fx, Aeq_e, Aub_e, Hvec, base, fix, beq, n6 = self._setup(cap, rhs)
        P0, P1 = self.parts[0], (self.parts[1] if n6 else None)
        warm, ub_best = bool(pool), math.inf
        pool, cols, hist, R = dict.fromkeys(pool or ()), {}, [], None
        for _ in range(maxit):
            keys = list(pool)
            for k in keys:
                if k not in cols:
                    cols[k] = self._column(E, k)
            od = sorted({k[:3] for k in keys})
            odi = {k: i for i, k in enumerate(od)}
            m = len(keys)
            zr = np.concatenate([cols[k][0] for k in keys]) if m else np.zeros(0, int)
            zc = np.repeat(np.arange(m), [len(cols[k][0]) for k in keys])
            Z = csr_matrix((np.concatenate([cols[k][1] for k in keys]) if m else np.zeros(0), (zr, zc)), shape=(NK * nr, m))
            OD = csr_matrix((np.ones(m), ([odi[k[:3]] for k in keys], np.arange(m))), shape=(len(od), m))
            odlam = np.array([-P0["Q"][i, j] if prt == 0 else 0.0 for prt, i, j in od])
            odrhs = np.array([n6 * P1["Q"][i, j] if prt == 1 else 0.0 for prt, i, j in od])
            Aub = vstack([hstack([csr_matrix(base[0].reshape(-1, 1)), Aub_e, Z]),
                          hstack([csr_matrix(odlam.reshape(-1, 1)), csr_matrix((len(od), A)), OD])], format="csr")
            bub = np.concatenate([Hvec - fix, odrhs])
            Aeq = hstack([csr_matrix(-P0["F"].on.reshape(-1, 1)), Aeq_e, csr_matrix((Aeq_e.shape[0], m))], format="csr")
            c = np.zeros(Aub.shape[1])
            c[0] = -1.0
            lp = linprog(c, A_ub=Aub, b_ub=bub, A_eq=Aeq, b_eq=beq, bounds=(0, None), method="highs")
            if lp.status != 0:
                raise RuntimeError(f"route-free master problem failed: {lp.message}")
            lam = lp.x[0]
            R = lam if R is None and not warm else R
            if R_only:
                return dict(R=float(lam) + n6, secs=round(time.time() - t0, 1))
            mu, nu = -lp.ineqlin.marginals[:NK * nr], lp.eqlin.marginals
            sig = dict(zip(od, -lp.ineqlin.marginals[NK * nr:]))
            new, ub = self._price(E, fx, Aub_e, mu, sig, nu, Hvec, add)
            ub_best = min(ub_best, ub)                 # every round's certificate is an upper bound; keep the smallest
            hist.append(dict(master=float(lam) + n6, ub=float(ub) + n6, cols=m, new=len(new), secs=round(time.time() - t0, 1)))
            if log:
                log(hist[-1])
            if not new or ub_best - lam <= tol * max(lam, 1.0):
                break
            pool.update(dict.fromkeys(new))
        x = lp.x
        return dict(R=None if R is None else float(R) + n6, master=float(lam) + n6, T1pp=float(ub_best) + n6,
                    gap=float((ub_best - lam) / lam), iters=len(hist), cols=m, history=hist, pool=pool, secs=round(time.time() - t0, 1),
                    lp=dict(rows=Aub.shape[0] + Aeq.shape[0], cols=Aub.shape[1], nnz=int(Aub.nnz + Aeq.nnz),
                            keys=sum(len(P_["pairs"]) for P_ in self.parts) * len(self.Bs)),
                    binding=price_list(net, self.res_list, mu, Aub[:NK * nr] @ x + fix, Hvec, top),
                    mu_min=float(mu.min()), dual_infeas=float(max(0.0, np.max(nu[self.hidx] - nu[self.tidx] - Aub_e.T @ mu))),
                    duals=(mu, nu), sol=dict(lam=float(lam), f=x[1:1 + A], z={k: float(v) for k, v in zip(keys, x[1 + A:]) if v > 1e-9}),
                    detour=self._detour(keys, lp, Aub, bub, Aeq, beq, lam))

    def _column(self, E, k):
        """Coefficients of column z_P (tasks/day) in the occupancy rows, E_b (1_P − 1_P0): (nonzero row indices, values)."""
        prt, i, j, arcs = k
        x = np.asarray(E[j][:, list(arcs)].sum(axis=1)).ravel() - np.asarray(E[j][:, self.parts[prt]["paths"][i]].sum(axis=1)).ravel()
        nz = np.nonzero(np.abs(x) > 1e-12)[0]
        return nz, x[nz]

    def _fix_nu(self, nu, ce):
        """Repairs ν to be strictly feasible for the empty-run costs ce (μ⁺·ẽ_a ≥ 0 on every arc): ν'_n = min_s [ν_s + d(s, n)],
        with d the shortest distance under ce.
        Method: a super source z with an edge of weight ν_s − min ν to every node s, and one Dijkstra run (of parallel arcs the
        cheaper is kept). ν' ≤ ν, and ν'_head − ν'_tail ≤ ce_a."""
        N, base = len(self.nodes), float(nu.min())
        order = np.lexsort((ce, self.hidx, self.tidx))
        t_, h_ = self.tidx[order], self.hidx[order]
        keep = order[np.r_[True, (t_[1:] != t_[:-1]) | (h_[1:] != h_[:-1])]]
        G = csr_matrix((np.r_[nu - base, ce[keep]], (np.r_[np.full(N, N), self.tidx[keep]], np.r_[np.arange(N), self.hidx[keep]])),
                       shape=(N + 1, N + 1))
        return base + dijkstra(G, directed=True, indices=[N])[0][:N]

    def _price(self, E, fx, Ae, mu, sig, nu, Hvec, add):
        """Pricing: for each B, shortest paths on the node graph from every origin (arc cost = column of μ⁺·E_b; of parallel
        arcs the cheaper is kept; the destination junction is included on both sides and cancels in the comparison); keys
        whose shortest path is cheaper than their key path (less the dual price σ of the OD row) enter as columns, the first
        `add` by q × improvement. Also computes the Lagrangian certificate
            UB = [μ⁺·Hvec − n6 (G6 + ν'·on6)] / (G0 + ν'·on0),  G = μ⁺·(F − X) + Σ q · shortest-path cost,
        μ⁺ = max(μ, 0), ν' = _fix_nu(ν): valid for any route and independent of how accurate the solver's duals are (proof in
        the paper's appendix)."""
        mu = np.maximum(mu, 0.0)
        nu = self._fix_nu(nu, np.asarray(Ae.T @ mu).ravel())
        cand, G = [], [float(mu @ f) for f in fx]
        for j in range(len(self.Bs)):
            w = E[j].T @ mu
            order = np.lexsort((w, self.hidx, self.tidx))
            t_, h_ = self.tidx[order], self.hidx[order]
            keep = order[np.r_[True, (t_[1:] != t_[:-1]) | (h_[1:] != h_[:-1])]]
            Gr = csr_matrix((w[keep], (self.tidx[keep], self.hidx[keep])), shape=(len(self.nodes),) * 2)
            arc_of = dict(zip(zip(self.tidx[keep].tolist(), self.hidx[keep].tolist()), keep.tolist()))
            for prt, P_ in enumerate(self.parts):
                sel = np.nonzero(P_["Q"][:, j] > 0)[0]
                if not len(sel):
                    continue
                srcs = np.unique(P_["o"][sel])
                dist, pred = dijkstra(Gr, directed=True, indices=srcs, return_predecessors=True)
                row = np.searchsorted(srcs, P_["o"][sel])
                sp, q = dist[row, P_["d"][sel]], P_["Q"][sel, j]
                G[prt] += float(q @ sp)
                kc = P_["Pinc"][sel] @ w - np.array([sig.get((prt, i, j), 0.0) for i in sel.tolist()])
                gain = kc - sp
                for x in np.nonzero(gain > 1e-9 * np.abs(kc) + 1e-15)[0]:
                    cand.append((q[x] * gain[x], prt, int(sel[x]), j, int(row[x]), int(P_["d"][sel[x]]), pred, arc_of))
        cand.sort(key=lambda c: -c[0])
        new = []
        for _, prt, i, j, r, n, pred, arc_of in cand[:add]:
            path = []
            while pred[r, n] >= 0:
                path.append(arc_of[(int(pred[r, n]), n)])
                n = int(pred[r, n])
            new.append((prt, i, j, tuple(path[::-1])))
        num = float(mu @ Hvec)
        den = G[0] + float(nu @ self.parts[0]["F"].on)
        if len(self.parts) > 1:
            num -= self.parts[1]["n6"] * (G[1] + float(nu @ self.parts[1]["F"].on))
        return new, (num / den if den > 0 else math.inf)

    def _detour(self, keys, lp, Aub, bub, Aeq, beq, lam):
        """Detour statistics: with λ held at or above the master value × (1 − 1e-7), finds within the column pool the solution
        with the least total detour length (the optimum is degenerate; this takes the one with the least detour).
        share = detoured loaded tasks / all loaded tasks (excluding direct lifts inside a crane span and tasks whose origin and
        destination are on the same node); extra_m = mean extra length per detoured task."""
        P_ = self.parts
        loaded = lam * P_[0]["Q"].sum() + sum(x["n6"] * x["Q"].sum() for x in P_[1:])
        m = len(keys)
        if not m:
            return dict(share=0.0, detoured_per_day=0.0, loaded_per_day=float(loaded), extra_m=0.0, extra_rel=0.0,
                        extra_km_per_day=0.0, stage2=True, avoided=[])
        l0 = np.array([P_[k[0]]["len0"][k[1]] for k in keys])
        dl = np.array([self.alen[list(k[3])].sum() for k in keys]) - l0
        c = np.zeros(Aub.shape[1])
        c[-m:] = dl
        lp2 = linprog(c, A_ub=Aub, b_ub=bub, A_eq=Aeq, b_eq=beq, bounds=[(lam * (1 - 1e-7), None)] + [(0, None)] * (Aub.shape[1] - 1),
                      method="highs")
        z = (lp2.x if lp2.status == 0 else lp.x)[-m:]
        tot = z.sum()
        avoided, road = collections.Counter(), lambda arcs: {self.net.arc[a][3] for a in arcs}
        for k, x in zip(keys, z):
            if x > 1e-9:
                for r in road(P_[k[0]]["paths"][k[1]]) - road(k[3]):
                    avoided[r] += x
        return dict(share=float(tot / loaded), detoured_per_day=float(tot), loaded_per_day=float(loaded),
                    extra_m=float(z @ dl / tot) if tot > 1e-9 else 0.0, extra_rel=float(z @ dl / (z @ l0)) if tot > 1e-9 else 0.0,
                    extra_km_per_day=float(z @ dl / 1000), stage2=lp2.status == 0,
                    avoided=[dict(road=r, name=res_name(self.net, ("r", r)), detoured_per_day=float(x)) for r, x in avoided.most_common(5)])

